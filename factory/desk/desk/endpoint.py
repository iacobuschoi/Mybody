"""말이 끝났나 — 받아쓴 글의 끝을 보고 "이어질 것 같은 말" 인지 가늠합니다(말 끝 기다리기, desk/vad.py).

조사 · 연결어미 · 접속사 · 머뭇거림("음", "그러니까")으로 끝나면 이어질 말로 보고 더 기다립니다.
틀려도 손해는 작습니다 — 이어질 말로 잘못 보면 hold_silence_s 만큼 늦을 뿐이고, 끝난 말로 잘못 보면 예전(자르기)과 같습니다.
그래서 헷갈리는 끝은 "이어질 말" 쪽으로 둡니다. 다만 "해 줘 · 할까 · 했어요" 같은 끝맺음은 먼저 끝난 말로 봅니다.
"""
from __future__ import annotations

import re

# 그 낱말 하나로 이어짐이 분명한 것 — 접속사 · 머뭇거림
WORDS = {"그리고", "그래서", "근데", "그런데", "그러면", "그럼", "그러니까", "아니면", "또", "또는", "혹시", "그니까",
         "음", "어", "저", "그", "저기", "뭐", "뭐냐", "막", "이제", "있잖아", "좀", "약간", "일단", "만약", "만약에"}

# 그 낱말 하나로 끝난 말 — 멈춤 말 · 대답 (끝 글자가 조사처럼 보여도)
DONE_WORDS = {"그만", "잠깐", "멈춰", "스톱", "스탑", "응", "네", "아니", "아니요", "됐어", "고마워", "좋아", "싫어"}

# 끝맺음 — 이걸로 끝나면 끝난 말(아래 이어짐 끝보다 먼저 봄)
ENDINGS = ("요", "죠", "줘", "까", "냐", "니", "래", "라", "자", "다", "지", "네", "군", "해", "봐", "와", "셔", "게",
           "어", "아", "야", "거든", "잖아", "는데요", "해요")

# 이어짐 — 조사 · 연결어미 (긴 것부터)
TAILS = ("에서", "으로", "이랑", "하고", "한테", "에게", "까지", "부터", "보다", "처럼", "으면", "는데", "은데", "인데",
         "니까", "지만", "거나", "든지", "려고", "도록", "다가", "면서", "고서", "어서", "아서",
         "은", "는", "이", "가", "을", "를", "에", "로", "랑", "의", "도", "만", "와", "과", "고", "면", "서")

_PUNCT_FINISHED = ("?", "!", "？", "！")
_PUNCT_OPEN = (",", "，", "…", "...", "-", "~")


def looks_unfinished(text: str) -> bool:
    t = (text or "").strip()
    if not t:
        return False
    if t.endswith(_PUNCT_OPEN):
        return True
    if t.endswith(_PUNCT_FINISHED):
        return False
    t = t.rstrip(". 。")
    words = re.findall(r"[가-힣A-Za-z0-9]+", t)
    if not words:
        return False
    w = words[-1]
    if w in DONE_WORDS:
        return False
    if w in WORDS:
        return True
    if w.endswith(ENDINGS):
        return False
    return len(w) >= 2 and w.endswith(TAILS)
